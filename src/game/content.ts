/** 按种子从危险描写池里取一句，避免同一舱每次都念同一段。 */
export function hazardLine(kind: HazardKind, visible: boolean, seed: number): string {
  const pool = visible ? HAZARD_TEXT[kind].field : HAZARD_TEXT[kind].hidden;
  return pool[Math.abs(seed) % pool.length];
}

